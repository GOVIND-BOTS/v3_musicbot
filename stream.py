
import asyncio
import logging
import time
from contextlib import suppress

from pyrogram import Client
from pyrogram.enums import ParseMode
from pyrogram.types import InputMediaPhoto

from pytgcalls import PyTgCalls
from pytgcalls.types import (
    MediaStream,
    AudioQuality,
    VideoQuality,
    Update,
)
from pytgcalls.types.stream import StreamEnded

from music import music_queue
from buttons import stream_buttons
from player_ui import now_playing_caption, stylize
from thumbnails import get_thumb
from database.mongodb import get_chat_settings


LOGGER = logging.getLogger(__name__)


class MusicStream:

    EVENT_DEBOUNCE = 1.5
    SKIP_EVENT_GUARD = 2.0

    def __init__(self, assistant: Client):
        self.assistant = assistant
        self.calls = PyTgCalls(assistant)

        self.locks = {}
        self.started = False
        self.player_messages = {}

        self._start_lock = asyncio.Lock()
        self._shutdown_lock = asyncio.Lock()

        self._last_ended_event = {}
        self._ignore_ended_until = {}

        self._register_handlers()

    # ----------------------------------
    # LOCK
    # ----------------------------------

    def lock_for(self, chat_id):
        if chat_id not in self.locks:
            self.locks[chat_id] = asyncio.Lock()

        return self.locks[chat_id]

    # ----------------------------------
    # PYTGCALLS EVENTS
    # ----------------------------------

    def _register_handlers(self):

        @self.calls.on_update()
        async def on_update(_, update: Update):

            if not isinstance(update, StreamEnded):
                return

            chat_id = update.chat_id
            now = time.monotonic()

            # Ignore delayed events generated by manual Skip.
            if now < self._ignore_ended_until.get(chat_id, 0):
                LOGGER.debug(
                    "Ignoring delayed StreamEnded event in %s",
                    chat_id,
                )
                return

            # Prevent duplicate end events from advancing twice.
            last_event = self._last_ended_event.get(
                chat_id,
                0,
            )

            if now - last_event < self.EVENT_DEBOUNCE:
                LOGGER.debug(
                    "Duplicate StreamEnded event ignored in %s",
                    chat_id,
                )
                return

            self._last_ended_event[chat_id] = now

            LOGGER.info(
                "Stream ended in chat %s",
                chat_id,
            )

            try:
                await self.play_next(
                    chat_id,
                    skip_current=False,
                )

            except Exception:
                LOGGER.exception(
                    "Automatic next-track playback failed in %s",
                    chat_id,
                )

    # ----------------------------------
    # START
    # ----------------------------------

    async def start(self):

        async with self._start_lock:

            if self.started:
                return

            await self.calls.start()
            self.started = True

            LOGGER.info("PyTgCalls started successfully.")

    # ----------------------------------
    # SETTINGS
    # ----------------------------------

    async def get_media_settings(self, chat_id):

        try:
            settings = await get_chat_settings(chat_id)

            return settings if isinstance(settings, dict) else {}

        except Exception:
            LOGGER.exception(
                "Failed to load media settings for %s",
                chat_id,
            )
            return {}

    def get_audio_quality(self, quality):

        quality = str(quality or "HIGH").upper()

        quality_map = {
            "LOW": "LOW",
            "MEDIUM": "MEDIUM",
            "HIGH": "HIGH",
        }

        enum_name = quality_map.get(quality, "HIGH")

        return getattr(
            AudioQuality,
            enum_name,
            AudioQuality.HIGH,
        )

    def get_video_quality(self, quality):

        quality = str(quality or "480p").lower()

        quality_map = {
            "360p": "SD_360p",
            "480p": "SD_480p",
            "720p": "HD_720p",
        }

        enum_name = quality_map.get(quality, "SD_480p")

        return getattr(
            VideoQuality,
            enum_name,
            VideoQuality.SD_480p,
        )

    # ----------------------------------
    # MEDIA
    # ----------------------------------

    def make_media(self, track, settings=None):

        if not isinstance(track, dict):
            raise TypeError("Track must be a dictionary.")

        settings = settings or {}

        url = track.get("url")

        if not url:
            raise ValueError("Track has no playable stream URL.")

        media_type = str(
            track.get("media_type", "audio")
        ).lower()

        audio_quality = self.get_audio_quality(
            settings.get("audio_quality", "HIGH")
        )

        if media_type == "video":

            video_quality = self.get_video_quality(
                settings.get("video_quality", "480p")
            )

            return MediaStream(
                url,
                audio_parameters=audio_quality,
                video_parameters=video_quality,
            )

        return MediaStream(
            url,
            audio_parameters=audio_quality,
            video_flags=MediaStream.Flags.IGNORE,
        )

    async def make_chat_media(self, chat_id, track):

        settings = await self.get_media_settings(chat_id)

        return self.make_media(
            track,
            settings,
        )

    # ----------------------------------
    # PLAYER CARD
    # ----------------------------------

    async def update_player_card(self, chat_id, track):

        message = self.player_messages.get(chat_id)

        if not message or not track:
            return

        try:

            video_id = (
                track.get("videoid")
                or track.get("video_id")
            )

            if not video_id:
                video_id = None

            thumb = None

            if video_id:
                thumb = await get_thumb(
                    video_id,
                    track.get("title", "Unknown Track"),
                    track.get("duration_text")
                    or track.get("duration", "Unknown"),
                    track.get("views", 0),
                    track.get("channel", "YouTube"),
                    stylize("Adisha Music"),
                    track.get(
                        "requested_by_name",
                        "Group member",
                    ),
                )

            caption = now_playing_caption(track)
            keyboard = stream_buttons(chat_id)

            if thumb:
                try:
                    await message.edit_media(
                        InputMediaPhoto(
                            media=thumb,
                            caption=caption,
                            parse_mode=ParseMode.HTML,
                        ),
                        reply_markup=keyboard,
                    )
                    return

                except Exception:
                    LOGGER.warning(
                        "Could not update player photo in %s",
                        chat_id,
                    )

            await message.edit_text(
                caption,
                parse_mode=ParseMode.HTML,
                reply_markup=keyboard,
                disable_web_page_preview=True,
            )

        except Exception:
            LOGGER.exception(
                "Player card update failed in %s",
                chat_id,
            )

    # ----------------------------------
    # PLAY NEXT
    # ----------------------------------

    async def play_next(
        self,
        chat_id: int,
        skip_current=False,
    ):

        await self.start()

        async with self.lock_for(chat_id):

            next_track = await music_queue.get_next(
                chat_id,
                skip_current=skip_current,
            )

            if not next_track:

                LOGGER.info("Queue empty in %s", chat_id)

                with suppress(Exception):
                    await self.calls.leave_call(chat_id)

                await music_queue.clear(chat_id)

                self.player_messages.pop(chat_id, None)

                return None

            try:

                media = await self.make_chat_media(
                    chat_id,
                    next_track,
                )

                await self.calls.play(
                    chat_id,
                    media,
                )

                LOGGER.info(
                    "Playing next track in %s: %s",
                    chat_id,
                    next_track.get("title", "Unknown"),
                )

            except Exception:

                LOGGER.exception(
                    "Failed to play next track in %s",
                    chat_id,
                )

                await music_queue.set_current(
                    chat_id,
                    None,
                )

                with suppress(Exception):
                    await self.calls.leave_call(chat_id)

                return None

        await self.update_player_card(
            chat_id,
            next_track,
        )

        return next_track

    # ----------------------------------
    # PLAY
    # ----------------------------------

    async def play(
        self,
        chat_id,
        track,
        media_type="audio",
    ):

        await self.start()

        if not isinstance(track, dict):
            raise TypeError("Track must be a dictionary.")

        item = dict(track)

        selected_type = (
            media_type
            or item.get("media_type", "audio")
        )

        item["media_type"] = (
            "video"
            if str(selected_type).lower() == "video"
            else "audio"
        )

        if not item.get("url"):
            raise ValueError("Track has no playable stream URL.")

        async with self.lock_for(chat_id):

            current = await music_queue.get_current(chat_id)

            if current:

                position = await music_queue.add(
                    chat_id,
                    item,
                )

                LOGGER.info(
                    "Track queued in %s at position %s: %s",
                    chat_id,
                    position,
                    item.get("title", "Unknown"),
                )

                return "queued"

            try:

                media = await self.make_chat_media(
                    chat_id,
                    item,
                )

                # Store current track before starting the stream.
                # This prevents another request from seeing an
                # empty queue state during playback startup.
                await music_queue.set_current(
                    chat_id,
                    item,
                )

                try:
                    await self.calls.play(
                        chat_id,
                        media,
                    )

                except Exception:
                    await music_queue.set_current(
                        chat_id,
                        None,
                    )
                    raise

            except Exception:

                LOGGER.exception(
                    "Failed to start playback in %s",
                    chat_id,
                )

                raise

        LOGGER.info(
            "%s started in %s: %s",
            item["media_type"].upper(),
            chat_id,
            item.get("title", "Unknown"),
        )

        return "playing"

    # ----------------------------------
    # PAUSE
    # ----------------------------------

    async def pause(self, chat_id):

        await self.start()

        async with self.lock_for(chat_id):

            if not await music_queue.get_current(chat_id):
                return False

            await self.calls.pause(chat_id)

            await music_queue.set_paused(
                chat_id,
                True,
            )

        return True

    # ----------------------------------
    # RESUME
    # ----------------------------------

    async def resume(self, chat_id):

        await self.start()

        async with self.lock_for(chat_id):

            if not await music_queue.get_current(chat_id):
                return False

            await self.calls.resume(chat_id)

            await music_queue.set_paused(
                chat_id,
                False,
            )

        return True

    # ----------------------------------
    # SKIP
    # ----------------------------------

    async def skip(self, chat_id):

        await self.start()

        # Ignore the delayed StreamEnded event caused by
        # replacing the currently playing stream.
        self._ignore_ended_until[chat_id] = (
            time.monotonic() + self.SKIP_EVENT_GUARD
        )

        return await self.play_next(
            chat_id,
            skip_current=True,
        )

    # ----------------------------------
    # STOP
    # ----------------------------------

    async def stop(self, chat_id):

        await self.start()

        async with self.lock_for(chat_id):

            self._ignore_ended_until[chat_id] = (
                time.monotonic() + self.SKIP_EVENT_GUARD
            )

            with suppress(Exception):
                await self.calls.leave_call(chat_id)

            await music_queue.clear(chat_id)

            self.player_messages.pop(chat_id, None)

            self._last_ended_event.pop(chat_id, None)

        LOGGER.info("Playback stopped in %s", chat_id)

        return True

    # ----------------------------------
    # REPLAY
    # ----------------------------------

    async def replay(self, chat_id):

        await self.start()

        async with self.lock_for(chat_id):

            track = await music_queue.get_current(chat_id)

            if not track:
                return None

            media = await self.make_chat_media(
                chat_id,
                track,
            )

            await self.calls.play(
                chat_id,
                media,
            )

            await music_queue.set_paused(
                chat_id,
                False,
            )

        return track

    # ----------------------------------
    # SHUTDOWN
    # ----------------------------------

    async def shutdown(self):

        async with self._shutdown_lock:

            if not self.started:
                return

            LOGGER.info("Shutting down music stream...")

            with suppress(Exception):
                await self.calls.stop()

            self.started = False


def setup_stream(assistant: Client):
    return MusicStream(assistant)
